/**
 * Contraste WCAG 2 entre dos colores hex (`#rrggbb` o `#rgb`). Fórmula de luminancia relativa de
 * WCAG 2.1 §1.4.3: texto normal necesita 4,5:1 (AA). Usado para fijar colores de categoría que
 * llevan texto blanco encima (fix-236-b).
 */
export function contrastRatio(a: string, b: string): number {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

function relativeLuminance(hex: string): number {
  const h = hex.replace('#', '');
  const full = h.length === 3 ? [...h].map((c) => c + c).join('') : h;
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(full.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
